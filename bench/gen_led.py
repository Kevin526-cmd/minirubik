import numpy as np, random, sys
POS={0:(1,1,1),1:(1,-1,1),2:(-1,-1,1),3:(1,1,-1),4:(1,-1,-1),5:(-1,-1,-1),6:(-1,1,-1),7:(-1,1,1)}
SRC=[[1,4,2,0,3,5,6],[0,1,2,4,5,6,3],[0,2,5,3,1,4,6]]
TW=[[1,2,0,2,1,0,0],[0,0,0,1,2,1,2],[0]*7]
def rot(axis,ang):
    c,s=round(np.cos(ang)),round(np.sin(ang)); x,y,z=axis
    K=np.array([[0,-z,y],[z,0,-x],[-y,x,0]]); return np.eye(3)*c+s*K+(1-c)*np.outer(axis,axis)
def rot120(d,ang):
    d=np.array(d)/np.sqrt(3); K=np.array([[0,-d[2],d[1]],[d[2],0,-d[0]],[-d[1],d[0],0]])
    return np.eye(3)*np.cos(ang)+np.sin(ang)*K+(1-np.cos(ang))*np.outer(d,d)
MOVES={0:((1,0,0),-np.pi/2,lambda p:p[0]==1),1:((0,0,1),np.pi/2,lambda p:p[2]==-1),2:((0,1,0),np.pi/2,lambda p:p[1]==-1)}
T=lambda v:tuple(int(round(x)) for x in v)
FACE={(0,1,0):'U',(0,-1,0):'D',(0,0,1):'F',(0,0,-1):'B',(1,0,0):'R',(-1,0,0):'L'}
COLIDX={'U':0,'D':1,'F':2,'B':3,'R':4,'L':5}
PAL=[0xFFFFFF,0xFFD500,0x00B000,0x0050FF,0xE00000,0xFF8000]  # white yellow green blue red orange
X0={'L':0,'F':9,'R':18,'B':27,'U':9,'D':9}; Y0={'U':2,'D':16,'L':9,'F':9,'R':9,'B':9}
def cell(p,n):
    f=FACE[n];x,y,z=p
    if f=='F': c,r=(x>0),(y<0)
    elif f=='R': c,r=(z<0),(y<0)
    elif f=='B': c,r=(x<0),(y<0)
    elif f=='L': c,r=(z>0),(y<0)
    elif f=='U': c,r=(x>0),(z>0)
    else: c,r=(x>0),(z<0)
    return X0[f]+4*c, Y0[f]+3*r
def slots(i):
    p=np.array(POS[i]); n0=np.array([0,p[1],0])
    return [T(n0),T(rot120(p,2*np.pi/3)@n0),T(rot120(p,4*np.pi/3)@n0)]
SLOT_PIX=[[ (lambda xy: xy[1]*35+xy[0])(cell(POS[i],slots(i)[k])) for k in range(3)] for i in range(8)]
CUBCOL=[[COLIDX[FACE[slots(c)[k]]] for k in range(3)] for c in range(8)]
ROT=[[(s-t)%3 for s in range(3)] for t in range(3)]
# check: all 24 pixels distinct
allp=[x for r in SLOT_PIX for x in r]; assert len(set(allp))==24
def render_po(p,o):
    img={}
    for i in range(8):
        for s in range(3): img[SLOT_PIX[i][s]]=CUBCOL[p[i]][ROT[o[i]][s]]
    return img
def move_po(p,o,f):
    return [p[SRC[f][i]] for i in range(7)]+[7],[(o[SRC[f][i]]+TW[f][i])%3 for i in range(7)]+[0]
# geometric sticker sim
def solved_geo():
    st={}
    for i in range(8):
        for n in slots(i): st[(POS[i],n)]=COLIDX[FACE[n]]
    return st
def move_geo(st,f):
    axis,ang,sel=MOVES[f];R=rot(np.array(axis),ang);out={}
    for (p,n),c in st.items():
        if sel(p): out[(T(R@np.array(p)),T(R@np.array(n)))]=c
        else: out[(p,n)]=c
    return out
def render_geo(st):
    return {(lambda xy:xy[1]*35+xy[0])(cell(p,n)):c for (p,n),c in st.items()}
random.seed(1)
