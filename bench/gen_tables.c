#define main ida_main
#include "../IDA_ripes.c"
#undef main

#define PER_LINE 16

static void c_array(FILE *f, const char *type, const char *name,
                    const char *dims, const void *data, int count, int wide)
{
    fprintf(f, "static const %s %s%s = {\n", type, name, dims);
    for (int i = 0; i < count; ++i) {
        unsigned v = wide ? ((const uint16_t *) data)[i]
                          : ((const uint8_t *) data)[i];
        fprintf(f, "%s%u,%s", i % PER_LINE ? " " : "    ", v,
                (i % PER_LINE == PER_LINE - 1 || i == count - 1) ? "\n" : "");
    }
    fprintf(f, "};\n\n");
}

static void s_array(FILE *f, const char *name, const char *comment,
                    const void *data, int count, int wide)
{
    if (wide)
        fprintf(f, "    .align 1\n");
    fprintf(f, "# %s (%d bytes)\n%s:\n", comment, count * (wide ? 2 : 1), name);
    for (int i = 0; i < count; ++i) {
        unsigned v = wide ? ((const uint16_t *) data)[i]
                          : ((const uint8_t *) data)[i];
        if (i % PER_LINE == 0)
            fprintf(f, "    %s ", wide ? ".half" : ".byte");
        fprintf(f, "%u%s", v,
                (i % PER_LINE == PER_LINE - 1 || i == count - 1) ? "\n" : ", ");
    }
    fprintf(f, "\n");
}

int main(int argc, char **argv)
{
    const char *h_path = argc > 1 ? argv[1] : "tables.h";
    const char *s_path = argc > 2 ? argv[2] : "tables.s";

    build_transitions();
    build_cubie_move();
    build_dist_p();
    build_dist_o();
    build_dist_po();

    for (int i = 0; i < PO_STATES; ++i)
        if (dist_po[i] == UINT8_MAX) {
            fprintf(stderr, "dist_po[%d] unvisited\n", i);
            return 1;
        }

    FILE *h = fopen(h_path, "w");
    if (!h) { perror(h_path); return 1; }
    fprintf(h, "/* Generated by bench/gen_tables.c. Do not edit. */\n"
               "#ifndef TABLES_H\n#define TABLES_H\n#include <stdint.h>\n\n");
    c_array(h, "uint16_t", "permutation", "[3][5040]", permutation, 3 * 5040, 1);
    c_array(h, "uint16_t", "orientation", "[3][729]", orientation, 3 * 729, 1);
    c_array(h, "uint8_t", "cubie_move", "[3][28]", cubie_move, 3 * 28, 0);
    c_array(h, "uint8_t", "dist_po", "[45360]", dist_po, PO_STATES, 0);
    c_array(h, "uint8_t", "dist_o", "[729]", dist_o, ORIENTATIONS, 0);
    fprintf(h, "#endif\n");
    fclose(h);

    FILE *s = fopen(s_path, "w");
    if (!s) { perror(s_path); return 1; }
    fprintf(s, "# Generated by bench/gen_tables.c. Do not edit.\n"
               "# Row f of permutation/orientation/cubie_move is a quarter "
               "turn of face f (0=R, 1=B, 2=D).\n"
               "    .data\n\n");
    s_array(s, "permutation", "uint16 permutation[3][5040]", permutation, 3 * 5040, 1);
    s_array(s, "orientation", "uint16 orientation[3][729]", orientation, 3 * 729, 1);
    s_array(s, "cubie_move", "uint8 cubie_move[3][28], c = position*4 + twist", cubie_move, 3 * 28, 0);
    s_array(s, "dist_o", "uint8 dist_o[729]", dist_o, ORIENTATIONS, 0);
    s_array(s, "dist_po", "uint8 dist_po[5040*9], index = P*9 + twistA*3 + twistB", dist_po, PO_STATES, 0);
    fclose(s);

    int total = 2 * 3 * 5040 + 2 * 3 * 729 + 3 * 28 + PO_STATES + ORIENTATIONS;
    printf("wrote %s and %s\n", h_path, s_path);
    printf("permutation %6d bytes\n", 2 * 3 * 5040);
    printf("orientation %6d bytes\n", 2 * 3 * 729);
    printf("cubie_move  %6d bytes\n", 3 * 28);
    printf("dist_po     %6d bytes\n", PO_STATES);
    printf("dist_o      %6d bytes\n", ORIENTATIONS);
    printf("total       %6d bytes (%.1f KiB of 128 KiB)\n", total, total / 1024.0);
    return 0;
}
